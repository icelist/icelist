def translate_spec_key(key: str) -> str:
    """规格 key 找静态俄文对照，找不到原样返回。"""
    return SPEC_KEY_RU.get(key.strip(), key)


def specs_bilingual(specs: dict) -> str:
    """把 specs dict 渲染成 '中文(俄文): 值 | ...' 形式。"""
    if not specs:
        return ""
    parts = []
    for k, v in specs.items():
        ru = SPEC_KEY_RU.get(str(k).strip())
        label = f"{k}({ru})" if ru else str(k)
        parts.append(f"{label}: {v}")
    return " | ".join(parts)
